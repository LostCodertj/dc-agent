CREATE TABLE IF NOT EXISTS dcgw_devices (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL DEFAULT 'Telefon',
  model VARCHAR(120) NOT NULL DEFAULT '',
  app_ver VARCHAR(20) NOT NULL DEFAULT '',
  dc_pkg VARCHAR(120) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL,
  last_seen DATETIME NULL,
  battery TINYINT NOT NULL DEFAULT -1,
  charging TINYINT NOT NULL DEFAULT 0,
  listener TINYINT NOT NULL DEFAULT 0,
  pending INT NOT NULL DEFAULT 0,
  revoked TINYINT NOT NULL DEFAULT 0,
  alerted TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS dcgw_pair (
  code CHAR(8) PRIMARY KEY,
  expires_at DATETIME NOT NULL,
  used TINYINT NOT NULL DEFAULT 0,
  created_by BIGINT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS dcgw_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  device_id INT UNSIGNED NOT NULL,
  pkg VARCHAR(120) NOT NULL DEFAULT '',
  title VARCHAR(200) NOT NULL DEFAULT '',
  text VARCHAR(800) NOT NULL DEFAULT '',
  amount DECIMAL(12,2) NULL,
  commission DECIMAL(12,2) NULL,
  direction ENUM('in','out','unknown') NOT NULL DEFAULT 'unknown',
  is_test TINYINT NOT NULL DEFAULT 0,
  posted_at DATETIME NOT NULL,
  received_at DATETIME NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'new',
  dup_of BIGINT UNSIGNED NULL,
  match_ref VARCHAR(64) NULL,
  decided_by BIGINT NULL,
  decided_at DATETIME NULL,
  note VARCHAR(255) NULL,
  UNIQUE KEY uq_uuid (uuid),
  KEY k_status (status),
  KEY k_posted (posted_at),
  KEY k_amount (amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS dcgw_log (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ts DATETIME NOT NULL,
  level VARCHAR(8) NOT NULL,
  device_id INT UNSIGNED NULL,
  msg VARCHAR(500) NOT NULL,
  KEY k_ts (ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS dcgw_audit (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ts DATETIME NOT NULL,
  admin_id BIGINT NOT NULL,
  event_id BIGINT UNSIGNED NULL,
  action VARCHAR(24) NOT NULL,
  reason VARCHAR(255) NULL,
  KEY k_ev (event_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
